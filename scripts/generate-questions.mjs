import { createHash } from "node:crypto";
import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceDirectory = path.join(root, "content", "questions");
const outputFile = path.join(root, "lib", "generatedQuestions.ts");
const expectedHeaders = [
  "exam_type", "category", "prompt", "choice1", "choice2", "choice3", "choice4",
  "correct_answer", "model_answer", "key_points", "explanation", "difficulty",
  "image_url", "tags", "source", "source_year", "reference_text", "code_snippet",
  "code_language", "image_urls"
];

await fs.mkdir(sourceDirectory, { recursive: true });
const files = (await fs.readdir(sourceDirectory))
  .filter((name) => name.toLowerCase().endsWith(".csv") && !name.startsWith("_"))
  .sort((a, b) => a.localeCompare(b));

const questions = [];
const seen = new Map();
const seenIds = new Map();
const errors = [];

for (const filename of files) {
  const source = (await fs.readFile(path.join(sourceDirectory, filename), "utf8"))
    .replace(/^\uFEFF/, "")
    .replace(/\r\n?/g, "\n");
  const rows = parseCsv(source);
  if (rows.length === 0) continue;
  const headers = rows[0].map((value) => value.trim());
  const missing = expectedHeaders.filter((header) => !headers.includes(header));
  if (missing.length) {
    errors.push(`${filename}: missing columns: ${missing.join(", ")}`);
    continue;
  }
  const column = Object.fromEntries(headers.map((header, index) => [header, index]));
  rows.slice(1).forEach((row, rowIndex) => {
    if (row.every((cell) => !cell.trim())) return;
    try {
      const value = (name) => (row[column[name]] ?? "").trim();
      const question = createQuestion(value, filename, rowIndex + 2);
      const duplicateKey = `${question.certificateId}:${question.examType}:${question.prompt.normalize("NFKC").replace(/\s+/g, " ").toLocaleLowerCase("ko-KR")}:${question.referenceText ?? ""}:${question.imageUrl ?? ""}`;
      if (seen.has(duplicateKey)) throw new Error(`duplicate question (first seen at ${seen.get(duplicateKey)})`);
      seen.set(duplicateKey, `${filename}:${rowIndex + 2}`);
      const idOwner = seenIds.get(question.id);
      if (idOwner) {
        const disambiguator = JSON.stringify([filename, question.examType, question.prompt, question.referenceText, question.imageUrl, question.source, "choices" in question ? question.choices : question.modelAnswer]);
        question.id = `csv-${createHash("sha256").update(disambiguator).digest("hex").slice(0, 16)}`;
        if (seenIds.has(question.id)) throw new Error(`question id collision (first seen at ${seenIds.get(question.id)})`);
      }
      seenIds.set(question.id, `${filename}:${rowIndex + 2}`);
      questions.push(question);
    } catch (error) {
      errors.push(`${filename}:${rowIndex + 2}: ${error.message}`);
    }
  });
}

if (errors.length) {
  console.error("Question CSV validation failed:\n" + errors.map((error) => `- ${error}`).join("\n"));
  process.exit(1);
}

// Keep the very large generated literal out of contextual union inference. Every
// row has already been validated by createQuestion above.
const serializedQuestions = JSON.stringify(questions);
const output = `import type { Question } from "./types";\n\n// Generated by \`npm run questions:generate\`. Do not edit this file directly.\n// JSON.parse avoids TypeScript constructing an enormous union for the data literal.\nexport const generatedQuestions = JSON.parse(${JSON.stringify(serializedQuestions)}) as Question[];\n`;
await fs.writeFile(outputFile, output, "utf8");
console.log(`Generated ${questions.length} question(s) from ${files.length} CSV file(s).`);

function createQuestion(value, filename, rowNumber) {
  const examType = value("exam_type").toUpperCase();
  if (!['WRITTEN_CBT', 'PRACTICAL_WRITTEN_RESPONSE'].includes(examType)) throw new Error("invalid exam_type");
  if (!value("category")) throw new Error("category is required");
  if (!value("prompt")) throw new Error("prompt is required");
  if (/문제\s*(?:복원\s*)?오류/.test(value("prompt")) || /실제\s*시험장에서는\s*모두\s*정답/.test(value("prompt"))) throw new Error("unrestored source question is not publishable");
  const difficulty = value("difficulty") || "medium";
  if (!["easy", "medium", "hard"].includes(difficulty)) throw new Error("difficulty must be easy, medium, or hard");
  const sourceYearText = value("source_year");
  const sourceYear = sourceYearText ? Number(sourceYearText) : undefined;
  if (sourceYearText && (!Number.isInteger(sourceYear) || sourceYear < 1900 || sourceYear > 2200)) throw new Error("invalid source_year");
  const imageUrls = splitList(value("image_urls"), /[|\n]/);
  const firstImage = value("image_url");
  const allImages = [...new Set([firstImage, ...imageUrls].filter(Boolean))];
  if (allImages.length > 6) throw new Error("at most 6 images are allowed");
  // Keep IDs stable when rows are reordered so saved answers and statistics survive rebuilds.
  const identity = `${filename}:${examType}:${value("prompt").normalize("NFKC")}`;
  const base = {
    id: `csv-${createHash("sha256").update(identity).digest("hex").slice(0, 16)}`,
    certificateId: value("certificate_id") || "information-processing-engineer",
    category: value("category"), examType, prompt: value("prompt"),
    explanation: value("explanation"), difficulty, version: 1, publicationStatus: "published",
    ...(allImages[0] ? { imageUrl: allImages[0] } : {}),
    ...(allImages.length > 1 ? { imageUrls: allImages.slice(1) } : {}),
    ...(value("reference_text") ? { referenceText: value("reference_text") } : {}),
    ...(value("code_snippet") ? { codeSnippet: value("code_snippet") } : {}),
    ...(value("code_language") ? { codeLanguage: value("code_language") } : {}),
    ...(splitList(value("tags"), /[|,;]/).length ? { tags: splitList(value("tags"), /[|,;]/) } : {}),
    ...(value("source") ? { source: value("source") } : {}),
    ...(sourceYear !== undefined ? { sourceYear } : {})
  };
  if (examType === "WRITTEN_CBT") {
    const choices = [1, 2, 3, 4].map((number) => value(`choice${number}`)).filter(Boolean);
    if (choices.length < 2) throw new Error("WRITTEN_CBT requires at least 2 consecutive choices");
    const normalizedChoices = choices.map((choice) => choice.normalize("NFKC").replace(/\s+/g, " ").trim().toLocaleLowerCase("ko-KR"));
    if (new Set(normalizedChoices).size !== normalizedChoices.length) throw new Error("WRITTEN_CBT choices must be unique");
    const answer = Number(value("correct_answer"));
    if (!Number.isInteger(answer) || answer < 1 || answer > choices.length) throw new Error("correct_answer is outside the choice range");
    return { ...base, choices, correctChoiceIndex: answer - 1 };
  }
  if (!value("model_answer")) throw new Error("PRACTICAL_WRITTEN_RESPONSE requires model_answer");
  return { ...base, modelAnswer: value("model_answer"), requiredKeyPoints: splitList(value("key_points"), /[|,;]/) };
}

function splitList(value, separator) {
  return [...new Set(value.split(separator).map((item) => item.trim()).filter(Boolean))];
}

function parseCsv(source) {
  const rows = []; let row = []; let cell = ""; let quoted = false;
  for (let index = 0; index < source.length; index += 1) {
    const char = source[index];
    if (char === '"' && quoted && source[index + 1] === '"') { cell += '"'; index += 1; }
    else if (char === '"') quoted = !quoted;
    else if (char === "," && !quoted) { row.push(cell); cell = ""; }
    else if ((char === "\n" || char === "\r") && !quoted) {
      if (char === "\r" && source[index + 1] === "\n") index += 1;
      row.push(cell); rows.push(row); row = []; cell = "";
    } else cell += char;
  }
  if (quoted) throw new Error("CSV contains an unclosed quote");
  if (cell || row.length) { row.push(cell); rows.push(row); }
  return rows;
}
